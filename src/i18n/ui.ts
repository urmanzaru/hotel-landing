export const ui: Record<Locale, Record<UiKey, string>> = { es, en };

export function t(
  locale: Locale,
  key: UiKey,
  params: Record<string, string | number> = {},
): string {
  const template = ui[locale][key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

/**
 * Textos del formulario de cotización para el navegador: solo las claves `quote.*` de UN idioma y sin el prefijo.
 * Se inyectan en la página como dato, así la isla no carga el diccionario completo de ambos idiomas.
 */
export function quoteMessages(locale: Locale): Record<string, string> {
  const prefix = 'quote.';
  return Object.fromEntries(
    Object.entries(ui[locale])
      .filter(([key]) => key.startsWith(prefix))
      .map(([key, value]) => [key.slice(prefix.length), value]),
  );
}
